import { createRequire } from 'node:module';
import { existsSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.POCKET_PLAYWRIGHT_MODULE || 'playwright');
const out = process.argv[2] || 'out/pull-cue-01';
const url = process.argv[3] || 'http://localhost:8080/demos/splash-kit/cue.html';
mkdirSync(out, { recursive: true });
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || ['/usr/bin/chromium', '/usr/bin/chromium-browser'].find(existsSync);
const browser = await chromium.launch({ executablePath, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = [], missing = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.status() >= 400) missing.push(new URL(r.url()).pathname); });
  await page.goto(url);
  const ready = () => page.waitForFunction(() => window.cueReview?.state.ready);
  await ready();
  const state = () => page.evaluate(() => cueReview.state);
  const seek = time => page.evaluate(time => cueReview.seek(time), time);
  const shot = name => page.locator('#cueStage').screenshot({ path: `${out}/${name}.png` });
  const before = await page.evaluate(() => JSON.stringify({ ...localStorage }));
  const receipt = JSON.stringify((await state()).results);
  assert.equal((await state()).count, 10);
  assert.equal((await state()).results[5].rarity, 'SSR');
  assert.equal((await state()).results[9].rarity, 'R');
  for (const [time, rank, name] of [[2.3, 0, 'blue'], [3.9, 1, 'silver'], [5.3, 2, 'gold'], [6.6, 3, 'rainbow']]) {
    await seek(time); const s = await state();
    assert.equal(s.lights.length, 10); assert.ok(s.lights.slice(0, 9).every(l => l.rank === 0 && !l.signal));
    assert.equal(s.lights[9].rank, rank); await shot(`ten-${name}`);
  }
  const timeline = await page.evaluate(() => cueReview.timeline), high = timeline.segments.find(s => s.high);
  await seek(high.start + high.quote - .1);
  assert.equal((await state()).phase, 'quote'); assert.equal(await page.locator('#hero').isVisible(), false); assert.equal(await page.locator('#cueQuote').isVisible(), true);
  await shot('quote-concealed');
  const closeAt = high.start + high.quote + high.entrance + high.push + .5;
  await seek(closeAt); assert.equal((await state()).phase, 'closeup'); assert.equal((await state()).zoom, 1.55); await shot('held-closeup');
  const pullAt = high.start + high.quote + high.entrance + high.push + high.close;
  await seek(pullAt + .7); assert.equal((await state()).phase, 'pullback'); await shot('pullback');
  await page.locator('#skip').click(); assert.equal((await state()).revealed, 10); await shot('ten-lineup');
  assert.equal(await page.locator('.roster .revealed').count(), 10);
  assert.equal(JSON.stringify((await state()).results), receipt);
  await page.locator('#play').click(); await page.waitForFunction(() => cueReview.state.elapsed > .15);
  await page.locator('#play').click(); const paused = (await state()).elapsed;
  await page.waitForTimeout(160); assert.equal((await state()).elapsed, paused);
  await page.locator('[data-count="1"]').click(); await ready();
  for (const tier of ['R', 'SR', 'SSR', 'UR']) {
    await page.locator(`[data-tier="${tier}"]`).click(); await ready();
    await seek(6); assert.equal((await state()).lights[0].rank, ['R', 'SR', 'SSR', 'UR'].indexOf(tier));
    await shot(`single-${tier.toLowerCase()}`);
    if (tier !== 'UR') assert.equal((await state()).results[0].rarity, tier);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await seek(3.2); const still = await page.locator('canvas').evaluate(c => c.toDataURL());
  await seek(3.3); assert.equal(await page.locator('canvas').evaluate(c => c.toDataURL()), still);
  const one = await page.evaluate(() => cueReview.timeline.segments[0]);
  await seek(one.start + one.quote + one.entrance + .5); assert.equal((await state()).zoom, 1);
  await page.locator('#skip').click(); assert.equal((await state()).phase, 'lineup');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('#area').selectOption('mushroom'); await ready();
  await seek(6); assert.equal((await state()).results[0].id, 'bowser'); await shot('mushroom-carrier');
  await page.locator('[data-count="10"]').click(); await ready();
  assert.equal((await state()).results.length, 10); assert.equal(await page.locator('[data-tier="R"]').isDisabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#area').selectOption('dream'); await ready();
  await seek(6.6); await shot('mobile-ten-rainbow'); await page.screenshot({ path: `${out}/mobile-page.png`, fullPage: true });
  const mobileHigh = await page.evaluate(() => cueReview.timeline.segments.find(s => s.high));
  await seek(mobileHigh.start + mobileHigh.quote + mobileHigh.entrance + mobileHigh.push + .5); await shot('mobile-closeup');
  await page.locator('#skip').click(); await shot('mobile-lineup');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  assert.equal(await page.evaluate(() => JSON.stringify({ ...localStorage })), before);
  assert.deepEqual(errors, []); assert.deepEqual(missing, []);
  const failure = await browser.newPage();
  await failure.route('**/display/*.webp', route => route.abort()); await failure.goto(url);
  await failure.waitForFunction(() => document.querySelector('#loading').textContent.includes('Reload to retry'));
  assert.equal(await failure.locator('#play').isDisabled(), true); await failure.close();
  console.log(JSON.stringify({ passed: true, errors, missing, storageUnchanged: true, quoteSeconds: high.quote, closeupSeconds: high.close, tenPullSeconds: timeline.total, checks: 'cumulative upgrades, tenth-only signal, saved result order, single and ten, quote concealment, held zoom and pullback, skip/replay/pause, reduced motion, both areas, 390px layout, readable asset failure' }));
} finally { await browser.close(); }
